export function getHeaderMenuCategories() {
  return HEADER_MENU_CATEGORIES.map((category) => ({
    ...category,
    tools: category.slugs.flatMap((slug) => {
      const tool = getToolBySlug(slug);
      if (!tool) return [];

      return [
        {
          tool,
          displayName: HEADER_MENU_DISPLAY_NAMES[slug],
        },
      ];
    }),
  }));
}
